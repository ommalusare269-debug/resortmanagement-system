-- Resort Management System Schema
-- Source of truth as per requirements

CREATE DATABASE IF NOT EXISTS resort_management;
USE resort_management;

-- 1. CUSTOMERS
CREATE TABLE IF NOT EXISTS CUSTOMERS (
    CustomerID INT AUTO_INCREMENT PRIMARY KEY,
    Name VARCHAR(100) NOT NULL,
    Phone VARCHAR(15) NOT NULL,
    Email VARCHAR(100) UNIQUE NOT NULL,
    Address VARCHAR(255),
    PasswordHash VARCHAR(255) NOT NULL, -- Added for authentication
    CreatedAt DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 2. ROOM_TYPES
CREATE TABLE IF NOT EXISTS ROOM_TYPES (
    RoomTypeID INT AUTO_INCREMENT PRIMARY KEY,
    TypeName VARCHAR(50) NOT NULL,
    Description VARCHAR(255),
    Capacity INT NOT NULL,
    Rate DECIMAL(10,2) NOT NULL
);

-- 3. ROOMS
CREATE TABLE IF NOT EXISTS ROOMS (
    RoomID INT AUTO_INCREMENT PRIMARY KEY,
    RoomTypeID INT NOT NULL,
    RoomNo VARCHAR(10) UNIQUE NOT NULL,
    FloorNo INT,
    Status VARCHAR(20) NOT NULL, -- AVAILABLE, OCCUPIED, MAINTENANCE, RESERVED
    FOREIGN KEY (RoomTypeID) REFERENCES ROOM_TYPES(RoomTypeID) ON DELETE RESTRICT
);

-- 4. BOOKINGS
CREATE TABLE IF NOT EXISTS BOOKINGS (
    BookingID INT AUTO_INCREMENT PRIMARY KEY,
    CustomerID INT NOT NULL,
    CheckInDate DATE NOT NULL,
    CheckOutDate DATE NOT NULL,
    NoOfGuests INT NOT NULL,
    BookingDate DATETIME DEFAULT CURRENT_TIMESTAMP,
    Status VARCHAR(20) NOT NULL, -- PENDING, CONFIRMED, CHECKED_IN, CHECKED_OUT, CANCELLED
    FOREIGN KEY (CustomerID) REFERENCES CUSTOMERS(CustomerID) ON DELETE RESTRICT
);

-- 5. ROOM_ALLOCATIONS
CREATE TABLE IF NOT EXISTS ROOM_ALLOCATIONS (
    AllocationID INT AUTO_INCREMENT PRIMARY KEY,
    BookingID INT NOT NULL,
    RoomID INT NOT NULL,
    CheckInDate DATE NOT NULL,
    CheckOutDate DATE NOT NULL,
    Rate DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (BookingID) REFERENCES BOOKINGS(BookingID) ON DELETE CASCADE,
    FOREIGN KEY (RoomID) REFERENCES ROOMS(RoomID) ON DELETE RESTRICT
);

-- 6. SERVICES
CREATE TABLE IF NOT EXISTS SERVICES (
    ServiceID INT AUTO_INCREMENT PRIMARY KEY,
    ServiceName VARCHAR(100) NOT NULL,
    Description VARCHAR(255),
    Charge DECIMAL(10,2) NOT NULL
);

-- 7. BOOKING_SERVICES
CREATE TABLE IF NOT EXISTS BOOKING_SERVICES (
    BookingServiceID INT AUTO_INCREMENT PRIMARY KEY,
    BookingID INT NOT NULL,
    ServiceID INT NOT NULL,
    Qty INT NOT NULL,
    Amount DECIMAL(10,2) NOT NULL, -- Automatically calculated
    FOREIGN KEY (BookingID) REFERENCES BOOKINGS(BookingID) ON DELETE CASCADE,
    FOREIGN KEY (ServiceID) REFERENCES SERVICES(ServiceID) ON DELETE RESTRICT
);

-- 8. STAFF
CREATE TABLE IF NOT EXISTS STAFF (
    StaffID INT AUTO_INCREMENT PRIMARY KEY,
    Name VARCHAR(100) NOT NULL,
    Role VARCHAR(50) NOT NULL, -- ADMIN, ACCOUNTANT, STAFF
    Phone VARCHAR(15) NOT NULL,
    Email VARCHAR(100) UNIQUE NOT NULL,
    PasswordHash VARCHAR(255) NOT NULL, -- Added for authentication
    Salary DECIMAL(10,2) NOT NULL
);

-- 9. INVOICES
CREATE TABLE IF NOT EXISTS INVOICES (
    InvoiceID INT AUTO_INCREMENT PRIMARY KEY,
    BookingID INT NOT NULL,
    InvoiceDate DATE NOT NULL,
    TotalAmount DECIMAL(12,2) NOT NULL,
    Discount DECIMAL(10,2) DEFAULT 0,
    GrandTotal DECIMAL(12,2) NOT NULL,
    FOREIGN KEY (BookingID) REFERENCES BOOKINGS(BookingID) ON DELETE CASCADE
);

-- 10. PAYMENTS
CREATE TABLE IF NOT EXISTS PAYMENTS (
    PaymentID INT AUTO_INCREMENT PRIMARY KEY,
    InvoiceID INT NOT NULL,
    PaymentDate DATE NOT NULL,
    Amount DECIMAL(12,2) NOT NULL,
    PaymentMode VARCHAR(50) NOT NULL, -- CASH, CARD, UPI, NET_BANKING
    TxnReference VARCHAR(100),
    Status VARCHAR(20) NOT NULL, -- PENDING, SUCCESS, FAILED, REFUNDED
    FOREIGN KEY (InvoiceID) REFERENCES INVOICES(InvoiceID) ON DELETE CASCADE
);
